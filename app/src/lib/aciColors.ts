export function getClosestAci(hex: string): number {
  if (!hex) return 7; // default white/black
  // simple euclidean distance in RGB
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  let minDist = Infinity;
  let bestIdx = 7;
  for (let i = 0; i < 256; i++) {
     const c = ACI_COLORS[i];
     const cr = parseInt(c.slice(1, 3), 16);
     const cg = parseInt(c.slice(3, 5), 16);
     const cb = parseInt(c.slice(5, 7), 16);
     const dist = (r - cr)**2 + (g - cg)**2 + (b - cb)**2;
     if (dist < minDist) {
        minDist = dist;
        bestIdx = i;
     }
  }
  return bestIdx;
}
